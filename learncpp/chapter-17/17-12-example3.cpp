// ============================================================
// 来源小节：17.12 Multidimensional C-style Arrays
// 示例说明：2d 数组的嵌套花括号初始化，以及部分初始化（未列出的元素被值初始化为 0）
//           （原 Example 8~9）。
// 原文链接：https://www.learncpp.com/cpp-tutorial/multidimensional-c-style-arrays/
// 预期输出：
//   15
//   0
// ============================================================
#include <iostream>

int main()
{
    // 完整的嵌套花括号初始化
    int array[3][5]
    {
        { 1, 2, 3, 4, 5 },     // row 0
        { 6, 7, 8, 9, 10 },    // row 1
        { 11, 12, 13, 14, 15 } // row 2
    };

    // 部分初始化：每行未列出的尾部元素被值初始化为 0
    int array2[3][5]
    {
        { 1, 2 },          // row 0: 1, 2, 0, 0, 0
        { 6, 7, 8 },       // row 1: 6, 7, 8, 0, 0
        { 11, 12, 13, 14 } // row 2: 11, 12, 13, 14, 0
    };

    std::cout << array[2][4] << '\n';  // 15
    std::cout << array2[0][3] << '\n'; // 0

    return 0;
}
